// Merges content/*.js (except tools) into public/categories.js for the browser and the engine.
// Usage: node content/build.js
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const dir = __dirname;
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.js') && !['build.js', 'validate.js'].includes(f)).sort();
execFileSync('node', [path.join(dir, 'validate.js'), ...files.map((f) => path.join(dir, f))], { stdio: 'inherit' });

const all = files.flatMap((f) => require(path.join(dir, f)));
const out = all.map(({ id, group, prompt, answers }) => ({ id, group, prompt, answers }));
const body = `// Generated by content/build.js from content/*.js — edit those files, not this one.
(function (root) {
const CATEGORIES = ${JSON.stringify(out)};
if (typeof module === 'object' && module.exports) module.exports = CATEGORIES;
else root.DUNG_CATEGORIES = CATEGORIES;
})(this);
`;
fs.writeFileSync(path.join(dir, '..', 'public', 'categories.js'), body);
const count = out.reduce((n, c) => n + Object.values(c.answers).flat().length, 0);
console.log(`wrote public/categories.js: ${out.length} categories, ${count} answers, ${(body.length / 1024).toFixed(0)} KB`);
